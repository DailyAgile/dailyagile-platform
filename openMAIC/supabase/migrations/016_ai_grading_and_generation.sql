-- 1. QUIZ_QUESTIONS EXTENSIONS — AI Generation Support
-- ============================================================================

-- Add AI generation fields to quiz_questions
ALTER TABLE quiz_questions
  ADD COLUMN IF NOT EXISTS ai_generated BOOLEAN DEFAULT false,
  ADD COLUMN IF NOT EXISTS generated_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS generation_prompt TEXT,
  ADD COLUMN IF NOT EXISTS difficulty VARCHAR(50) DEFAULT 'intermediate'
    CHECK (difficulty IN ('easy', 'intermediate', 'hard')),
  ADD COLUMN IF NOT EXISTS model_answer TEXT,
  ADD COLUMN IF NOT EXISTS rubric TEXT,
  ADD COLUMN IF NOT EXISTS code_language VARCHAR(50),
  ADD COLUMN IF NOT EXISTS starter_code TEXT,
  ADD COLUMN IF NOT EXISTS model_solution TEXT,
  ADD COLUMN IF NOT EXISTS question_type VARCHAR(50)
    CHECK (question_type IN ('multiple', 'short_answer', 'essay', 'code'));

CREATE INDEX IF NOT EXISTS idx_quiz_questions_ai_generated ON quiz_questions(ai_generated);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_generated_at ON quiz_questions(generated_at DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_questions_difficulty ON quiz_questions(difficulty);

