/**
 * Update quiz
 */
export async function updateQuiz(
  quizId: string,
  instructorEmail: string,
  updates: {
    title?: string;
    description?: string;
    time_limit_minutes?: number;
    attempt_limit?: number;
    pass_threshold?: number;
  }
) {
  try {
    const supabase = getSupabaseClient();

    // Verify ownership
    const { data: quiz, error: checkError } = await supabase
      .from('quizzes')
      .select('id, instructor_id')
      .eq('id', quizId)
      .single();

    if (checkError || !quiz || quiz.instructor_id !== instructorEmail) {
      log.warn(`Unauthorized update attempt for quiz ${quizId}`);
      return null;
    }

    // Update quiz
    const { data: updated, error: updateError } = await supabase
      .from('quizzes')
      .update({
        ...updates,
        updated_at: new Date().toISOString(),
      })
      .eq('id', quizId)
      .select()
      .single();

    if (updateError) {
      log.error('Error updating quiz:', updateError);
      return null;
    }

    log.info(`✅ Quiz updated: ${quizId}`);
    return updated;
  } catch (error) {
    log.error('Error in updateQuiz:', error);
    return null;
  }
}

/**
 * List instructor's quizzes
 */
export async function listInstructorQuizzes(
  instructorEmail: string,
  options: {
    page?: number;
    limit?: number;
    search?: string;
    status?: 'active' | 'archived' | 'deleted';
  } = {}
) {
  try {
    const supabase = getSupabaseClient();
    const page = options.page || 1;
    const limit = Math.min(options.limit || 20, 100);
    const offset = (page - 1) * limit;

    let query = supabase
      .from('quizzes')
      .select('id, title, description, total_questions, total_points, created_at, updated_at', {
        count: 'exact',
      })
      .eq('instructor_id', instructorEmail)
      .order('created_at', { ascending: false })
      .range(offset, offset + limit - 1);

    // Apply filters
    if (options.search) {
      query = query.ilike('title', `%${options.search}%`);
    }

    if (options.status === 'active') {
      query = query.eq('is_active', true).is('deleted_at', null);
    } else if (options.status === 'archived') {
      query = query.eq('is_active', false);
    } else if (options.status === 'deleted') {
      query = query.not('deleted_at', 'is', null);
    }

    const { data: quizzes, error, count } = await query;

    if (error) {
      log.error('Error listing quizzes:', error);
      return null;
    }

    return {
      quizzes: quizzes || [],
      total: count || 0,
      page,
      limit,
      pages: Math.ceil((count || 0) / limit),
    };
  } catch (error) {
    log.error('Error in listInstructorQuizzes:', error);
    return null;
  }
}

/**
 * Soft delete quiz
 */
export async function softDeleteQuiz(quizId: string, instructorEmail: string) {
  try {
    const supabase = getSupabaseClient();

    // Verify ownership
    const { data: quiz, error: checkError } = await supabase
      .from('quizzes')
      .select('id, instructor_id')
      .eq('id', quizId)
      .single();

    if (checkError || !quiz || quiz.instructor_id !== instructorEmail) {
      log.warn(`Unauthorized delete attempt for quiz ${quizId}`);
      return null;
    }

    // Mark as deleted
    const { data: updated, error: deleteError } = await supabase
      .from('quizzes')
      .update({
        deleted_at: new Date().toISOString(),
        is_active: false,
      })
      .eq('id', quizId)
      .select()
      .single();

    if (deleteError) {
      log.error('Error deleting quiz:', deleteError);
      return null;
    }

    log.info(`✅ Quiz soft-deleted: ${quizId}`);
    return updated;
  } catch (error) {
    log.error('Error in softDeleteQuiz:', error);
    return null;
  }
}
