ALTER TABLE quiz_answers
  ADD COLUMN IF NOT EXISTS grading_status VARCHAR(50) DEFAULT 'ungraded'
    CHECK (grading_status IN ('ungraded', 'ai_graded', 'instructor_reviewed', 'instructor_overridden')),
  ADD COLUMN IF NOT EXISTS ai_score NUMERIC,
  ADD COLUMN IF NOT EXISTS ai_feedback TEXT,
  ADD COLUMN IF NOT EXISTS ai_graded_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS instructor_score NUMERIC,
  ADD COLUMN IF NOT EXISTS instructor_feedback TEXT,
  ADD COLUMN IF NOT EXISTS is_instructor_graded BOOLEAN DEFAULT false,
  ADD COLUMN IF NOT EXISTS graded_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ;

